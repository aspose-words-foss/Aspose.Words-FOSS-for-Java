    /// <param name="doc">Test document.</param>
    /// <returns>ImageData xml part.</returns>
    private static org.w3c.dom.Node getImageDataDocx(Document doc) throws Exception
    {
        final String IMAGE_DATA_PATH = "w:body/w:p/w:r/w:pict/v:shape/v:imagedata";
        DocxExportContext context = new DocxExportContext(doc);
        org.w3c.dom.Node imageData = context.getXmlNode(IMAGE_DATA_PATH);
        return imageData;
    }

