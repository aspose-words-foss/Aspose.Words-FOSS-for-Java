    /// <summary>
    /// Create document with image.
    /// </summary>
    /// <param name="title">Value to be set for Title attribute of ImagweData element.</param>
    /// <param name="isLinkedOnly">When true shape in document is linked only.</param>
    /// <param name="shapeType">Type of the shape.</param>
    /// <returns></returns>
    private static Document createImageDocument(String title, boolean isLinkedOnly, /*ShapeType*/int shapeType) throws Exception
    {
        String picPath = TestUtil.buildTestFileName("ExportDocx\\TestJira13261.gif");
        Document doc = new Document();
        DocumentBuilder builder = new DocumentBuilder(doc);
        Shape linkedOnly = new Shape(builder.getDocument(), shapeType);
        linkedOnly.setWrapType(WrapType.INLINE);
        ImageData ingData = linkedOnly.getImageData();

        if (null != title)
            ingData.setTitle(title);

        if (isLinkedOnly)
            ingData.setSourceFullName(picPath);
        else
            ingData.setImage(picPath);

        builder.insertNode(linkedOnly);
        return doc;
    }

    /// <summary>
    /// Get Title attribute and check existence.
    /// </summary>
    /// <param name="doc">Test document.</param>
    /// <param name="format">Format in which the document is saved.</param>
    /// <param name="exist">When True check Title attribute exist, when false check Title skipped.</param>
    private static void checkTitleAttribute(Document doc, /*SaveFormat*/int format, boolean exist) throws Exception
    {
        org.w3c.dom.Node imageData = null;

        switch(format)
        {
            case SaveFormat.DOCX:
                imageData = getImageDataDocx(doc);
                break;
            default:
                Assert.fail("Invalid format.");
                break;
        }

        org.w3c.dom.Attr atrTitle = (org.w3c.dom.Attr) imageData.getAttributes().getNamedItem("o:title");

        if (exist)
            msAssert.isNotNull(atrTitle);
        else
            msAssert.isNull(atrTitle);
    }

    /// <summary>
    /// Get ImageData xml part for "Docx" document.
