    /// <summary>
    /// IExpandableAttr
    /// </summary>
    @ReservedForInternalUse @Deprecated
    public void /*IExpandableAttr.*/collapse(IExpandableAttr parentAttr)
    {
        if (parentAttr == null)
            return;

        TabStopCollection parentTabStops = (TabStopCollection)parentAttr;
        for (int i = 0; i < parentTabStops.getCount(); i++)
        {
            TabStop parentTabStop = parentTabStops.get(i);

            int childTabStopIndex = getIndexByPosition(parentTabStop.getPosition());
            if (childTabStopIndex >= 0)
            {
                // Remove a child tab if a same tab exists in the base.
                TabStop childTabStop = this.get(childTabStopIndex);
                if (childTabStop.equals(parentTabStop))
                    removeByIndex(childTabStopIndex);
            }
            else
            {
                    // If a tab exists in the base, but not in child, add a "clear" tab to the child.
                    add(parentTabStop.getPosition(), TabAlignment.CLEAR, TabLeader.NONE);
            }
        }
    }

    /// <summary>
    /// Removes adjacent clearing tab if they are within 25 twips.
    /// </summary>
    /// <remarks>
    /// AM. It seems Word removes such tabs when does TabStopCollection expanding.
    /// Otherwise we failed to write revision properly, for example in TestDefect15121.docx.
    /// </remarks>
    void removeClearingWithTolerance()
    {
        if (getCount() == 0)
            return;

        notifyChanging();

        for (int i = getCount() - 1; i > 0; i--)
        {
            TabStop tab = this.get(i);
            TabStop prevTab = this.get(i - 1);

            // Remove clear tab stop, if it is within 25 twips from the previous clear tab stop.
            if (tab.isClear() && prevTab.isClear() && (tab.getPositionTwips() - prevTab.getPositionTwips() <= 25))
                removeByIndex(i);
        }
    }

