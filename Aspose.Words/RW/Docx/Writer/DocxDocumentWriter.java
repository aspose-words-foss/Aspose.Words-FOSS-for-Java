/// <summary>
/// Writers the main document to an OOXML part.
/// </summary>
class DocxDocumentWriter extends DocxDocumentWriterBase
{
    DocxDocumentWriter(DocxWriter writer, TempFiler tempFiler)
    {
    	super(writer, writer.getDocument(), writer.getWarningCallback());
	
        mTempFiler = tempFiler;
    }

    protected /*override*/ OpcPackagePart doCreateDocumentPart() throws Exception
    {
        OpcPackagePart part = getPackage().createChildPart(null, "/word/document.xml", getDocumentPartContentType(), getRelTypes().getOfficeDocument());
        // Create either FileStream or MemoryStream depending on SaveOption.TempFolder.
        // Avoid to recreate MemoryStream.
        if (mTempFiler.isTempFilesEnabled())
            part.setStream(mTempFiler.getNewStream());
        return part;
    }

    private String getDocumentPartContentType()
    {
        switch (getSaveInfo().getSaveFormat())
        {
            case SaveFormat.DOCX:
            case SaveFormat.FLAT_OPC:
                return DocxContentType.DOCUMENT;
            case SaveFormat.DOCM:
            case SaveFormat.FLAT_OPC_MACRO_ENABLED:
                return DocxContentType.DOCUMENT_MACRO_ENABLED;
            case SaveFormat.DOTX:
            case SaveFormat.FLAT_OPC_TEMPLATE:
                return DocxContentType.TEMPLATE;
            case SaveFormat.DOTM:
            case SaveFormat.FLAT_OPC_TEMPLATE_MACRO_ENABLED:
                return DocxContentType.TEMPLATE_MACRO_ENABLED;
            default:
                throw new IllegalStateException("Unexpected file format.");
        }
    }

    protected /*override*/ void doWrite() throws Exception
    {
        DocxCustomXmlPartWriter.write(this);
        writeDocument();
        DocxVbaWriter.write(this);
        DocxCustomizationsWriter.write(this);
        writeGlossary();
        writeTheme();
    }

    private void writeDocument() throws Exception
    {
        Document doc = getSaveInfo().Document;
        ProgressProcessor = new SavingProgressProcessor(doc, getSaveOptions(), SavingStageType.SAVING);

        DocxBuilder builder = getCurrentBuilder();
        builder.startDocumentWithStandardNamespaces("w:document");

        if (getCompliance() == OoxmlComplianceCore.ISO_STRICT)
            builder.writeAttribute("w:conformance", "strict");

        if (getSaveOptions().getExportGeneratorName())
            builder.writeComment(msString.format(" Generated by {0} ", AssemblyConstants.GENERATOR_NAME));

        DocxBackgroundWriter.write(this);

        builder.startElement("w:body");
        writeSections(doc);

        // Only section properties for the last section should be written from here.
        // Section properties for the other sections are written in the last paragraphs of these sections.
        if (getCurrentSection().isLastChild())
            NrxSectPrWriter.write(getCurrentSection(), this);

        builder.endElement("w:body");   // body

        builder.endDocument();

        ProgressProcessor.complete();
        // Reset reference to avoid progress call invocation for the glossary document.
        ProgressProcessor = null;
    }

    private void writeGlossary() throws Exception
    {
        CompositeNode glossary = getSaveInfo().Document.getGlossaryDocument();
        if ((glossary == null) || (!glossary.hasChildNodes()))
            return;

        DocxGlossaryWriter glossaryWriter = new DocxGlossaryWriter(getWriter());
        glossaryWriter.write();
    }

    private void writeTheme() throws Exception
    {
        writeTheme(getSaveInfo().Document.getThemeInternal(), this, false);
    }

    static void writeTheme(Theme theme, DocxDocumentWriterBase writer, boolean isThemeOverride) throws Exception
    {
        if (theme == null)
            return;

        String contentType = isThemeOverride ? DocxContentType.THEME_OVERRIDE : DocxContentType.THEME;
        String relType = isThemeOverride ? writer.getRelTypes().getThemeOverride() : writer.getRelTypes().getTheme();
        int partNumber = writer.getNextEmbeddedPartNumber(relType);
        String partName = isThemeOverride
            ? msString.format("../theme/themeOverride{0}.xml", partNumber)
            : msString.format("theme/theme{0}.xml", partNumber);

        OpcPackagePart parentPart = isThemeOverride ? writer.getCurrentBuilder().getPart() : writer.getDocumentPart();

        OpcPackagePart newThemePart;
        // If theme is not modified and format is not changed, we use unparsed stream.
        if (theme.isModified() ||
            !msString.equals(theme.getThemeNamespace(), DocxNamespaces.getNamespace(DocxNamespace.DRAWING_ML_MAIN,
                writer.getCompliance() == OoxmlComplianceCore.ISO_STRICT)))
        {
            String dummyRelId = null;
            Ref<String> referenceToDummyRelId = new Ref<String>(dummyRelId);
            DocxBuilder builder = writer.createChildPartAndBuilder(parentPart, partName, contentType, relType,
                /*out*/ referenceToDummyRelId);
            dummyRelId = referenceToDummyRelId.get();
            newThemePart = builder.getPart();

            writer.pushBuilder(builder);
            ThemeWriter.write(writer, theme, isThemeOverride);
            writer.popBuilder();
        }
        else
        {
            newThemePart = writer.getPackage().createChildPart(parentPart, partName, contentType, relType);
            newThemePart.setStream(theme.getThemePart().getStream());
        }

        writeUnparsedRels(theme.getThemePart(), theme.getRelatedParts(), newThemePart, writer);
    }

    
    @ReservedForInternalUse @Deprecated
    public /*new*/ Document getDocument() { return (Document)super.getDocument(); }

    private /*final*/ TempFiler mTempFiler;
}

