import com.aspose.IAnyXmlBuilder;
import com.aspose.StringUtil;
import com.aspose.FormatterPal;
import com.aspose.ms.System.Text.msStringBuilder;
import com.aspose.ms.System.msString;
import com.aspose.ms.System.StringComparison;


/// <summary>
/// Helper methods to writes document properties to DOCX, WordML, HTML and RTF.
/// This class is static.
/// </summary>
/*static*/ class NrxDocPropertiesWriter
{
	/* Simulation of static class by using private constructor */
	private NrxDocPropertiesWriter()
	{}

    /// <summary>
    /// Write built-in and custom document properties in the WordML and HTML format.
    /// isInsideHtmlComment is used when writing in HTML since properties are written within
    /// comments and HTML comments don't allow "--" inside.
    /// </summary>
    static void writeWml(Document doc, IAnyXmlBuilder builder, boolean isInsideHtmlComment) throws Exception
    {
        writeBuiltInPropertiesWml(doc.getBuiltInDocumentProperties(), builder, isInsideHtmlComment);
        writeCustomPropertiesWml(doc.getCustomDocumentProperties(), builder, isInsideHtmlComment);
    }

    private static void writeBuiltInPropertiesWml(BuiltInDocumentProperties props, IAnyXmlBuilder builder, boolean isInsideHtmlComment) throws Exception
    {
        builder.startElement("o:DocumentProperties");

        writeOptionalStringElement(builder, "o:Title", props.getTitle(), isInsideHtmlComment);
        writeOptionalStringElement(builder, "o:Subject", props.getSubject(), isInsideHtmlComment);
        writeOptionalStringElement(builder, "o:Author", props.getAuthor(), isInsideHtmlComment);
        writeOptionalStringElement(builder, "o:Keywords", props.getKeywords(), isInsideHtmlComment);
        writeOptionalStringElement(builder, "o:Description", props.getComments(), isInsideHtmlComment);
        writeOptionalStringElement(builder, "o:LastAuthor", props.getLastSavedBy(), isInsideHtmlComment);
        builder.writeElement("o:Revision", props.getRevisionNumber());

        // o:AppName is the name of the application that last updated the document.
        // Word and Excel do not update this element.
        // MS Word even treats o:AppName element in WordML as an error, so we do not write it here.

        builder.writeElement("o:TotalTime", props.getTotalEditingTime());
        builder.writeOptionalElement("o:LastPrinted", props.getLastPrintedInternal());
        builder.writeOptionalElement("o:Created", props.getCreatedTimeInternal());
        builder.writeOptionalElement("o:LastSaved", props.getLastSavedTimeInternal());
        builder.writeElement("o:Pages", props.getPages());
        builder.writeElement("o:Words", props.getWords());
        builder.writeElement("o:Characters", props.getCharacters());
        writeOptionalStringElement(builder, "o:Category", props.getCategory(), isInsideHtmlComment);

        // o:PresentationFormat element is not used in WordML.
        // Possible values: "On-screen Show", "A4 Paper (210x297 mm), etc.". Probably is for PowerPoint only.

        writeOptionalStringElement(builder, "o:Manager", props.getManager(), isInsideHtmlComment);
        writeOptionalStringElement(builder, "o:Company", props.getCompany(), isInsideHtmlComment);

        // TODO 3 o:Guid element is skipped now.
        // Don't know where to get it, have not seen it in WordML generated by MS Word yet.

        writeOptionalStringElement(builder, "o:HyperlinkBase", props.getHyperlinkBase(), isInsideHtmlComment);

        DocumentProperty bytesProp = props.get(PropertyName.BYTES);
        if ((bytesProp.getDefaultValueInternal() == null) && (bytesProp.toInt() > 0))
            builder.writeElement("o:Bytes", props.getBytes());

        builder.writeElement("o:Lines", props.getLines());
        builder.writeElement("o:Paragraphs", props.getParagraphs());
        builder.writeElement("o:CharactersWithSpaces", props.getCharactersWithSpaces());

        builder.writeElement("o:Version", NrxXmlUtil.versionNumberToXml(props.getVersion()));

        builder.endElement(); //o:DocumentProperties
    }

    private static void writeOptionalStringElement(IAnyXmlBuilder builder, String elementName, String value, boolean isInsideHtmlComment)
    {
        builder.writeOptionalElement(elementName, prepareStringValue(value, isInsideHtmlComment));
    }

    private static String prepareStringValue(String value, boolean isInsideHtmlComment)
    {
        // Adding "\\&#x2d;\\&#x2d;" gives the same result here. Let's add resilience with a minus and a single space.
        // This will safely handle sequences of more than two minuses.
        // MS Word writes two minuses as "&#45;-". How can we escase this way? Maybe we should switch to using 
        // XmlTextWriter.WriteComment when writing anything inside comments.
        return isInsideHtmlComment ? value.replace("--", "- ") : value;
    }

    private static void writeCustomPropertiesWml(CustomDocumentProperties props, IAnyXmlBuilder builder, boolean isInsideHtmlComment) throws Exception
    {
        if (!hasWritableProperties(props))
            return;

        builder.startElement("o:CustomDocumentProperties");
        
        for (DocumentProperty prop : (Iterable<DocumentProperty>) props)
        {
            if (isWritableProperty(prop))
                writeCustomPropertyWml(prop, builder, isInsideHtmlComment);
        }
        
        builder.endElement(); //o:CustomDocumentProperties
    }

    private static void writeCustomPropertyWml(DocumentProperty prop, IAnyXmlBuilder builder, boolean isInsideHtmlComment) throws Exception
    {
        builder.startElement(makePropertyNameWml(prop.getName()));

        switch (prop.getType())
        {
            case PropertyType.BOOLEAN:
                builder.writeAttributeString("dt:dt", "boolean");
                builder.writeString(prop.toBool() ? "1" : "0");
                break;
            case PropertyType.NUMBER:
                builder.writeAttributeString("dt:dt", "float");
                if (StringUtil.hasChars(prop.getLinkTarget()))
                    builder.writeAttributeString("link", prop.getLinkTarget());
                builder.writeString(prop.toString());
                break;
            case PropertyType.DOUBLE:
                builder.writeAttributeString("dt:dt", "float");
                if (StringUtil.hasChars(prop.getLinkTarget()))
                    builder.writeAttributeString("link", prop.getLinkTarget());
                builder.writeString(FormatterPal.doubleToStr(prop.toDouble()));
                break;
            case PropertyType.STRING:
                builder.writeAttributeString("dt:dt", "string");
                // Only a text property can be a link target.
                if (StringUtil.hasChars(prop.getLinkTarget()))
                    builder.writeAttributeString("link", prop.getLinkTarget());
                builder.writeString(prepareStringValue(prop.toString(), isInsideHtmlComment));
                break;
            case PropertyType.DATE_TIME:
                builder.writeAttributeString("dt:dt", "dateTime.tz");
                builder.writeString(FormatterPal.dateTimeToXmlUtc(prop.toDateTimeInternal()));
                break;
            default:
                throw new IllegalStateException("Unexpected property type.");
        }

        builder.endElement();
    }

    /// <summary>
    /// Only alphanumeric strings are allowed as element names in XML.
    /// All other characters should be converted to hex representation.
    /// For example "Some name" should be converted to "Some_x0020_Name".
    /// </summary>
    private static String makePropertyNameWml(String name)
    {
        StringBuilder sb = new StringBuilder("o:");

        for (int i = 0; i < name.length(); i++)
        {
            char ch = name.charAt(i);
            if (isValidChar(ch, i == 0))
                sb.append(ch);
            else
            {
                msStringBuilder.append(sb, "_x");
                msStringBuilder.append(sb, FormatterPal.intToStrX4(ch));
                sb.append('_');
            }
        }

        return sb.toString();
    }

    /// <summary>
    /// Determines whether the specified character is a valid character for a property name.
    /// For details, see https://www.w3.org/TR/REC-xml/#NT-NameStartChar.
    /// Note, that we excluded colon marked as permissible but it produced corrupted document.
    /// </summary>
    private static boolean isValidChar(char ch, boolean isFirst)
    {
        // WORDSNET-26913 According to the documentation, a property name
        // can start with a letter or underline.
        if (Character.isLetter(ch) || ch == '_')
            return true;
        // Next characters can also contain digits, dashes and periods
        // without converting to hex.
        if (!isFirst && (Character.isDigit(ch) || ch == '-' || ch == '.'))
            return true;

        return false;
    }

    static boolean hasWritableProperties(CustomDocumentProperties props)
    {
        for (DocumentProperty prop : (Iterable<DocumentProperty>) props)
        {
            if (isWritableProperty(prop))
                return true;
        }
        return false;
    }

    /// <summary>
    /// Check if the custom document property is one of the properties we are writing to DOCX, RTF and WML.
    /// MS Word filters out some of the custom properties found in DOC files.
    /// </summary>
    static boolean isWritableProperty(DocumentProperty prop)
    {
        if (msString.startsWith(prop.getName(), "_PID_", StringComparison.ORDINAL))
            return false;

        return isWritableType(prop.getType());
    }

    private static boolean isWritableType(/*PropertyType*/int type)
    {
        switch (type)
        {
            case PropertyType.BOOLEAN:
            case PropertyType.DATE_TIME:
            case PropertyType.DOUBLE:
            case PropertyType.NUMBER:
            case PropertyType.STRING:
                return true;
            case PropertyType.OTHER:
            default:
                return false;
        }
    }

    static void writeNoLineBreaks(DocPr docPr, NrxXmlBuilder builder, String lang)
    {
        if (StringUtil.hasChars(docPr.NoLineBreaksAfter))
        {
            builder.writeElementWithAttributes(
                "w:noLineBreaksAfter",
                "w:lang", lang,
                "w:val", docPr.NoLineBreaksAfter);
        }

        if (StringUtil.hasChars(docPr.NoLineBreaksBefore))
        {
            builder.writeElementWithAttributes(
                "w:noLineBreaksBefore",
                "w:lang", lang,
                "w:val", docPr.NoLineBreaksBefore);
        }
    }
}

