/**
 * <p>The <b>com.aspose.words</b> package provides 
 * classes for generating, converting, modifying, rendering and printing Microsoft Word documents 
 * without utilizing Microsoft Word.</p>
 * 
 * <p>Aspose.Words is written completely in Java. Microsoft Word is not required in order to use Aspose.Words.</p>
 * 
 * <p>The classes in the <b>com.aspose.words</b> package
 * borrow best practices from two well-known frameworks: Microsoft Word Automation and System.Xml.
 * A document in Aspose.Words is represented by a tree of nodes, much like in XML DOM.
 * Where possible, class, method and property names match those found in Microsoft Word Automation. </p>
 * 
 * <p>The main classes in this namespace are:</p>
 *  
 * <list type="bullet">
 * <item>{@link com.aspose.words.Document} is the main class of the object
 * model that represents a Microsoft Word document.</item>
 * 
 * <item><{@link com.aspose.words.DocumentBuilder} provides an
 * easy way to insert content and formatting into a document.</item>
 * 
 * <item><{@link com.aspose.words.Node} is the base class for all nodes
 * in the document.</item>
 * 
 * <item>{@link com.aspose.words.CompositeNode} is the base class
 * for all nodes of the document that can contain other nodes, for example
 * {@link com.aspose.words.Paragraph}, {@link com.aspose.words.Section} and
 * {@link com.aspose.words.Table}.</item>
 * </list>
 * 
 * <java>
 * <p>The <b>com.aspose.words</b> package also contains classes that form
 * the reporting engine of Aspose.Words. The reporting engine allows to quickly 
 * and easily populate documents designed in Microsoft Word with data from 
 * various data sources such as <b>java.sql.ResultSet</b>, <b>array of ResultSets</b>, 
 * {@link com.aspose.words.net.System.Data.DataSet} or an <b>array of values</b>.</p>
 *
 * <p>The {@link com.aspose.words.MailMerge} object which provides access to the reporting functionality
 * is available via the {@link com.aspose.words.Document#getMailMerge} property.</p>
 */
package com.aspose.words;