    private void init(String format, double value, int defPrecision)
    {
        init(format);
        mValue = value;
        this.mDefPrecision = defPrecision;
        long bits = BitConverter.doubleToInt64Bits(value);
        this.mPositive = bits >= 0;
        bits &= Long.MAX_VALUE;
        if (bits == 0)
        {
            this.mDecPointPos = 1;
            this.mDigitsLen = 0;
            this.mPositive = true;
            return;
        }

        int e = (int)(bits >> DOUBLE_BITS_EXPONENT_SHIFT);
        long m = bits & DOUBLE_BITS_MANTISSA_MASK;
        if (e == DOUBLE_BITS_EXPONENT_MASK)
        {
            this.mNaN = m != 0;
            this.mInfinity = m == 0;
            return;
        }

        int expAdjust = 0;
        if (e == 0)
        {
            // We need 'm' to be large enough so we won't lose precision.
            e = 1;
            int scale = scaleOrder(m);
            if (scale < DOUBLE_DEF_PRECISION)
            {
                expAdjust = scale - DOUBLE_DEF_PRECISION;
                m *= getTenPowerOf(-expAdjust);
            }
        }
        else
        {
            m = (m + DOUBLE_BITS_MANTISSA_MASK + 1) * 10;
            expAdjust = -1;
        }

        // multiply the mantissa by 10 ^ N
        /*ulong*/ long lo = m & 0xFFFFFFFFL;
        /*ulong*/ long hi = /*(ulong)*/m >>> 32;
        /*ulong*/ long lo2 = MANTISSA_BITS_TABLE[e];
        /*ulong*/ long hi2 = lo2 >>> 32;
        lo2 = (((/*uint*/long)lo2) & 0xFFFFFFFFL);
        /*ulong*/ long mm = hi * lo2 + lo * hi2 + ((lo * lo2) >>> 32);
        long res = (long)(hi * hi2 + (mm >>> 32));
        while (res < SEVENTEEN_DIGITS_THRESHOLD)
        {
            mm = (mm & /*uint.MaxValue*/0xffffffffL) * 10;
            res = res * 10 + (long)(mm >> 32);
            expAdjust--;
        }
        if ((mm & 0x80000000L) != 0)
        {
            res++;
        }

        int order = DOUBLE_DEF_PRECISION + 2;
        this.mDecPointPos = TENS_EXPONENT_TABLE[e] + expAdjust + order;

        // Rescale 'res' to the initial precision (15-17 for doubles).
        int initialPrecision = initialFloatingPrecision();
        if (order > initialPrecision)
        {
            long val = getTenPowerOf(order - initialPrecision);
            res = (res + (val >> 1)) / val;
            order = initialPrecision;
        }
        if (res >= getTenPowerOf(order))
        {
            order++;
            this.mDecPointPos++;
        }

        initDecHexDigits(res);
        this.mOffset = countTrailingZeros();
        this.mDigitsLen = order - this.mOffset;
    }

