    private static void zeroTrimEnd(StringBuilder sb, boolean canEmpty)
    {
        int len = 0;
        for (int i = sb.length() - 1; (canEmpty ? i >= 0 : i > 0); i--)
        {
            if (sb.charAt(i) != '0')
            {
                break;
            }
            len++;
        }

        if (len > 0)
        {
            sb.delete((sb.length() - len), (sb.length() - len) + (len));
        }
    }

    private static boolean isZeroOnly(StringBuilder sb)
    {
        for (int i = 0; i < sb.length(); i++)
        {
            if (Character.isDigit(sb.charAt(i)) && sb.charAt(i) != '0')
            {
                return false;
            }
        }
        return true;
    }

    private static void appendNonNegativeNumber(StringBuilder sb, int v)
    {
        if (v < 0)
        {
            throw new IllegalArgumentException();
        }

        int i = scaleOrder(v) - 1;
        do
        {
            int n = v / (int)getTenPowerOf(i);
            sb.append((char)('0' | n));
            v -= (int)getTenPowerOf(i--) * n;
        }
        while (i >= 0);
    }

