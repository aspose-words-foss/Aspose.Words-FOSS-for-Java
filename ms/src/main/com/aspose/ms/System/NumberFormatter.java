    // minDigits is in the range 1..3
    private void appendExponent(/*NumberFormatInfo*/DecimalFormatSymbols nfi, int exponent, int minDigits)
    {
        if (this.mSpecifierIsUpper || this.mSpecifier == 'R')
        {
            if (this.mSpecifier == 'F')
                return;
            append('E');
        }
        else
        {
            append('e');
        }

        if (exponent >= 0)
        {
            append(/*nfi.PositiveSign*/'+');
        }
        else
        {
            append(nfi.getMinusSign());
            exponent = -exponent;
        }

        if (exponent == 0)
        {
            append('0', minDigits);
        }
        else if (exponent < 10)
        {
            append('0', minDigits - 1);
            append((char)('0' | exponent));
        }
        else
        {
            /*uint*/long hexDigit = fastToDecHex(exponent);
            if (exponent >= 100 || minDigits == 3)
            {
                append((char)('0' | (hexDigit >>> 8)));
            }
            append((char)('0' | ((hexDigit >>> 4) & 0xf)));
            append((char)('0' | (hexDigit & 0xf)));
        }
    }

    private void appendOneDigit(int start)
    {
        if (this.mInd == this.mCbuf.length)
        {
            resize(this.mInd + 10);
        }

        start += this.mOffset;
        /*uint*/long v;
        if (start < 0)
        {
            v = 0;
        }
        else if (start < 8)
        {
            v = this.mVal1;
        }
        else if (start < 16)
        {
            v = this.mVal2;
        }
        else if (start < 24)
        {
            v = this.mVal3;
        }
        else if (start < 32)
        {
            v = this.mVal4;
        }
        else
        {
            v = 0;
        }
        v >>>=  (start & 0x7) << 2;
        this.mCbuf[this.mInd++] = (char)('0' | v & 0xf);
    }

    private void appendDigits(int start, int end)
    {
        if (start >= end)
        {
            return;
        }

        int i = this.mInd + (end - start);
        if (i > this.mCbuf.length)
        {
            resize(i + 10);
        }
        this.mInd = i;

        end += this.mOffset;
        start += this.mOffset;

        for (int next = start + 8 - (start & 0x7);; start = next, next += 8)
        {
            /*uint*/long v;
            if (next == 8)
            {
                v = this.mVal1;
            }
            else if (next == 16)
            {
                v = this.mVal2;
            }
            else if (next == 24)
            {
                v = this.mVal3;
            }
            else if (next == 32)
            {
                v = this.mVal4;
            }
            else
            {
                v = 0;
            }
            v >>>=  (start & 0x7) << 2;
            if (next > end)
            {
                next = end;
            }

            this.mCbuf[--i] = (char)('0' | v & 0xf);
            switch (next - start)
            {
                case 8:
                    this.mCbuf[--i] = (char)('0' | (v >>>=  4) & 0xf);
                    /*goto case 7;*/
                case 7:
                    this.mCbuf[--i] = (char)('0' | (v >>>=  4) & 0xf);
                    /*goto case 6;*/
                case 6:
                    this.mCbuf[--i] = (char)('0' | (v >>>=  4) & 0xf);
                    /*goto case 5;*/
                case 5:
                    this.mCbuf[--i] = (char)('0' | (v >>>=  4) & 0xf);
                    /*goto case 4;*/
                case 4:
                    this.mCbuf[--i] = (char)('0' | (v >>>=  4) & 0xf);
                    /*goto case 3;*/
                case 3:
                    this.mCbuf[--i] = (char)('0' | (v >>>=  4) & 0xf);
                    /*goto case 2;*/
                case 2:
                    this.mCbuf[--i] = (char)('0' | (v >>>=  4) & 0xf);
                    /*goto case 1;*/
                case 1:
                    if (next == end)
                    {
                        return;
                    }
                    continue;
            }
        }
    }

    private void appendDigits(int start, int end, StringBuilder sb)
    {
        if (start >= end)
        {
            return;
        }

        int i = sb.length() + (end - start);
        sb.setLength(i);

        end += this.mOffset;
        start += this.mOffset;

        for (int next = start + 8 - (start & 0x7);; start = next, next += 8)
        {
            /*uint*/long v;
            if (next == 8)
            {
                v = this.mVal1;
            }
            else if (next == 16)
            {
                v = this.mVal2;
            }
            else if (next == 24)
            {
                v = this.mVal3;
            }
            else if (next == 32)
            {
                v = this.mVal4;
            }
            else
            {
                v = 0;
            }
            v >>>= (start & 0x7) << 2;
            if (next > end)
            {
                next = end;
            }
            sb.setCharAt(--i, (char)('0' | v & 0xf));
            switch (next - start)
            {
                case 8:
                    sb.setCharAt(--i, (char)('0' | (v >>>= 4) & 0xf));
                    /*goto case 7;*/
                case 7:
                    sb.setCharAt(--i, (char)('0' | (v >>>= 4) & 0xf));
                    /*goto case 6;*/
                case 6:
                    sb.setCharAt(--i, (char)('0' | (v >>>= 4) & 0xf));
                    /*goto case 5;*/
                case 5:
                    sb.setCharAt(--i, (char)('0' | (v >>>= 4) & 0xf));
                    /*goto case 4;*/
                case 4:
                    sb.setCharAt(--i, (char)('0' | (v >>>= 4) & 0xf));
                    /*goto case 3;*/
                case 3:
                    sb.setCharAt(--i, (char)('0' | (v >>>= 4) & 0xf));
                    /*goto case 2;*/
                case 2:
                    sb.setCharAt(--i, (char)('0' | (v >>>= 4) & 0xf));
                    /*goto case 1;*/
                case 1:
                    if (next == end)
                    {
                        return;
                    }
                    continue;
            }
        }
    }

