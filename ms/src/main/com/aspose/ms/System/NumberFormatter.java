    private void multiply10(int count)
    {
        if (count <= 0 || this.mDigitsLen == 0)
        {
            return;
        }

        this.mDecPointPos += count;
    }

    private void divide10(int count)
    {
        if (count <= 0 || this.mDigitsLen == 0)
        {
            return;
        }

        this.mDecPointPos -= count;
    }

