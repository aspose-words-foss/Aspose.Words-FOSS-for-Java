    // Translate an unsigned long to hexadecimal digits.
    private void initDecHexDigits(long value)
    {
        if (value >= HUNDRED_MILLION)
        {
            long div1 = value / HUNDRED_MILLION;
            value -= HUNDRED_MILLION * div1;
            if (div1 >= HUNDRED_MILLION)
            {
                int div2 = (int)(div1 / HUNDRED_MILLION);
                div1 = div1 - div2 * (long)HUNDRED_MILLION;
                this.mVal3 = toDecHex(div2);
            }
            if (div1 != 0)
            {
                this.mVal2 = toDecHex((int)(div1));
            }
        }
        if (value != 0)
        {
            this.mVal1 = toDecHex((int)value);
        }
    }

    // Helper to translate an int in the range 0 .. 9999 to its
    // Hexadecimal digits representation.
    private static /*uint*/long fastToDecHex(int val)
    {
        if (val < 100)
        {
            return (/*uint*/long)DEC_HEX_DIGITS[val];
        }

        // Uses 2^19 (524288) to compute val / 100 for val < 10000.
        int v = (val * 5243) >> 19;
        return (/*uint*/long)((DEC_HEX_DIGITS[v] << 8) | DEC_HEX_DIGITS[val - v * 100]);
    }

    // Helper to translate an int in the range 0 .. 99999999 to its
    // Hexadecimal digits representation.
    private static /*uint*/long toDecHex(int val)
    {
        /*uint*/long res = 0;
        if (val >= 10000)
        {
            int v = val / 10000;
            val -= v * 10000;
            res = ((fastToDecHex(v) << 16) & 0xFFFFFFFFL);
        }
        return (res & 0xFFFFFFFFL) | (fastToDecHex(val) & 0xFFFFFFFFL);
    }

    // Helper to count number of hexadecimal digits in a number.
    private static int fastDecHexLen(int val)
    {
        if (val < 0x100)
        {
            if (val < 0x10)
            {
                return 1;
            }
            return 2;
        }
        if (val < 0x1000)
        {
            return 3;
        }
        return 4;
    }

    private static int decHexLen(/*uint*/long val)
    {
        if ((val & 0xFFFFFFFFL) < 0x10000)
        {
            return fastDecHexLen((int)(val & 0xFFFFFFFFL));
        }
        return 4 + fastDecHexLen((int)(val >>> 16));
    }

