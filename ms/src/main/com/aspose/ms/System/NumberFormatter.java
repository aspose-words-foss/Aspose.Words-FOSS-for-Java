    private String formatRoundtrip(double origval, /*NumberFormatInfo*/DecimalFormatSymbols nfi)
    {
        NumberFormatter nfc = getClone();
        if (origval >= MIN_ROUNDTRIP_VAL && origval <= MAX_ROUNDTRIP_VAL)
        {
            String shortRep = formatGeneral(this.mDefPrecision, nfi);
            //JAVA-simplified: was double.Parse(shortRep, nfi)
            if (origval == Double.parseDouble(shortRep))
            {
                return shortRep;
            }
        }
        return nfc.formatGeneral(this.mDefPrecision + 2, nfi);
    }

    private String formatGeneral(int precision, /*NumberFormatInfo*/DecimalFormatSymbols nfi)
    {
        boolean enableExp;
        if (precision == -1)
        {
            enableExp = isFloatingSource();
            precision = this.mDefPrecision;
        }
        else
        {
            enableExp = true;
            if (precision == 0)
            {
                precision = this.mDefPrecision;
            }
            roundPos(precision);
        }

        int intDigits = this.mDecPointPos;
        int digits = this.mDigitsLen;
        int decDigits = digits - intDigits;

        if ((intDigits > precision || intDigits <= -4) && enableExp)
        {
            return formatExponential(digits - 1, nfi, 2);
        }

        if (decDigits < 0)
        {
            decDigits = 0;
        }
        if (intDigits < 0)
        {
            intDigits = 0;
        }
        resetCharBuf(decDigits + intDigits + 3);

        if (!this.mPositive)
        {
            append(nfi.getMinusSign());
        }

        if (intDigits == 0)
        {
            append('0');
        }
        else
        {
            appendDigits(digits - intDigits, digits);
        }

        if (decDigits > 0)
        {
            append(nfi.getDecimalSeparator());
            appendDigits(0, decDigits);
        }

        return new String(this.mCbuf, 0, this.mInd);
    }

    private String formatExponential(int precision, /*NumberFormatInfo*/DecimalFormatSymbols nfi, int expDigits)
    {
        int digits = this.mDigitsLen;
        int exponent = this.mDecPointPos - 1;
        int lastDigit = precision + this.mDecPointPos + 1;
        boolean haveExponent = (exponent > 8 || exponent < 0);
        if (haveExponent)
        {
            this.mDecPointPos = 1;
            lastDigit = precision + 1;
        }

        resetCharBuf(lastDigit + 1);

        if (!this.mPositive)
        {
            append(nfi.getMinusSign());
        }

        appendDigits(digits - this.mDecPointPos, digits);

        if (precision > 0)
        {
            append(nfi.getDecimalSeparator());
            appendDigits(digits - lastDigit, digits - this.mDecPointPos);
        }

        // Fix for round like in .Net
        String prefix = "";
        if (!haveExponent && lastDigit > 0 && this.mCbuf[lastDigit]>'5')
        {
            prefix = "1";
            this.mCbuf[lastDigit] = '0';
            lastDigit--;
            do
            {
                // scip decimal point
                if (this.mCbuf[lastDigit] == '.')
                    lastDigit--;

                if (this.mCbuf[lastDigit]<'9')
                {
                    this.mCbuf[lastDigit]++;
                    prefix = "";
                    break;
                }
                else
                {
                    this.mCbuf[lastDigit] = '0';
                    lastDigit--;
                }

                // work with minus sign
                if (!this.mPositive && this.mCbuf[lastDigit] == '-')
                {
                    this.mCbuf[lastDigit] = '1';
                    prefix = "-";
                    break;
                }
            } while (lastDigit > 0);
        }

        appendExponent(nfi, exponent, expDigits);

        if (haveExponent)
            return new String(this.mCbuf, 0, this.mInd);
        else
            return prefix + new String(this.mCbuf, 0, this.mInd - 1);
    }

    private String formatCustom(String format, /*NumberFormatInfo*/DecimalFormatSymbols nfi)
    {
        boolean p = this.mPositive;
        int offset = 0;
        int length = 0;
        boolean[] referenceToP = { p };
        int[] referenceToOffset = { offset };
        int[] referenceToLength = { length };
        CustomInfo.getActiveSection(format, /*ref*/ referenceToP, isZero(), /*ref*/ referenceToOffset, /*ref*/ referenceToLength);
        p = referenceToP[0];
        offset = referenceToOffset[0];
        length = referenceToLength[0];
        if (length == 0)
        {
            return this.mPositive ? "" : String.valueOf(nfi.getMinusSign());
        }
        this.mPositive = p;

        CustomInfo info = CustomInfo.parse(format, offset, length);
        StringBuilder sbInt = new StringBuilder(info.getIntegerDigits() * 2);
        StringBuilder sbDec = new StringBuilder(info.getDecimalDigits() * 2);
        StringBuilder sbExp = (info.isUseExponent() ? new StringBuilder(info.getExponentDigits() * 2) : null);

        int diff = 0;

        if (info.getPercents() > 0)
        {
            multiply10(2 * info.getPercents());
        }
        if (info.getPermilles() > 0)
        {
            multiply10(3 * info.getPermilles());
        }

        if (info.getDividePlaces() > 0)
        {
            divide10(info.getDividePlaces());
        }

        boolean expPositive = true;
        if (info.isUseExponent() && (info.getDecimalDigits() > 0 || info.getIntegerDigits() > 0))
        {
            if (!isZero())
            {
                roundPos(info.getDecimalDigits() + info.getIntegerDigits());
                diff -= this.mDecPointPos - info.getIntegerDigits();
                this.mDecPointPos = info.getIntegerDigits();
            }

            expPositive = diff <= 0;
            appendNonNegativeNumber(sbExp, diff < 0 ? -diff : diff);
        }
        else
        {
            roundDecimal(info.getDecimalDigits());
        }

        if (info.getIntegerDigits() != 0 || !isZeroInteger())
        {
            appendIntegerString(getIntegerDigits(), sbInt);
        }

        appendDecimalString(getDecimalDigits(), sbDec);

        if (info.isUseExponent())
        {
            if (info.getDecimalDigits() <= 0 && info.getIntegerDigits() <= 0)
            {
                this.mPositive = true;
            }

            if (sbInt.length() < info.getIntegerDigits())
            {
                msStringBuilder.insert(sbInt, 0, '0', info.getIntegerDigits() - sbInt.length());
            }

            while (sbExp.length() < info.getExponentDigits() - info.getExponentTailSharpDigits())
            {
                sbExp.insert(0, '0');
            }

            if (expPositive && !info.isExponentNegativeSignOnly())
            {
                sbExp.insert(0, /*nfi.PositiveSign*/'+');
            }
            else if (!expPositive)
            {
                sbExp.insert(0, nfi.getMinusSign());
            }
        }
        else
        {
            if (sbInt.length() < info.getIntegerDigits() - info.getIntegerHeadSharpDigits())
            {
                msStringBuilder.insert(sbInt, 0, '0', info.getIntegerDigits() - info.getIntegerHeadSharpDigits() - sbInt.length());
            }
            if (info.getIntegerDigits() == info.getIntegerHeadSharpDigits() && isZeroOnly(sbInt))
            {
                sbInt.delete((0), (0) + (sbInt.length()));
            }
        }

        zeroTrimEnd(sbDec, true);
        while (sbDec.length() < info.getDecimalDigits() - info.getDecimalTailSharpDigits())
        {
            sbDec.append('0');
        }
        if (sbDec.length() > info.getDecimalDigits())
        {
            sbDec.delete((info.getDecimalDigits()), (info.getDecimalDigits()) + (sbDec.length() - info.getDecimalDigits()));
        }

        return info.format(format, offset, length, nfi, this.mPositive, sbInt, sbDec, sbExp);
    }

