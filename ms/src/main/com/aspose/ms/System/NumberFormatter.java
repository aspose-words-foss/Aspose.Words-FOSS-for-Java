    private void roundPos(int pos)
    {
        roundBits(this.mDigitsLen - pos);
    }

    private void roundDecimal(int decimals)
    {
        roundBits(this.mDigitsLen - this.mDecPointPos - decimals);
    }

    private void roundBits(int shift)
    {
        if (shift <= 0)
        {
            return;
        }

        if (shift > this.mDigitsLen)
        {
            this.mDigitsLen = 0;
            this.mDecPointPos = 1;
            this.mVal1 = this.mVal2 = this.mVal3 = this.mVal4 = 0;
            this.mPositive = true;
            return;
        }
        shift += this.mOffset;
        this.mDigitsLen += this.mOffset;
        while (shift > 8)
        {
            this.mVal1 = this.mVal2;
            this.mVal2 = this.mVal3;
            this.mVal3 = this.mVal4;
            this.mVal4 = 0;
            this.mDigitsLen -= 8;
            shift -= 8;
        }
        shift = (shift - 1) << 2;
        /*uint*/long v = this.mVal1 >>> shift;
        /*uint*/long rem16 = v & 0xf;
        this.mVal1 = ((v ^ rem16) << shift)  & 0xFFFFFFFFL;

        if ((rem16 & 0xFFFFFFFFL) >= 0x5)
        {
            this.mVal1 |= 0x99999999L >> (28 - shift);
            addOneToDecHex();
            int newlen = decHexLen();
            this.mDecPointPos = this.mDecPointPos + newlen - this.mDigitsLen;
            this.mDigitsLen = newlen;
        }
        removeTrailingZeros();
    }

    private void removeTrailingZeros()
    {
        this.mOffset = countTrailingZeros();
        this.mDigitsLen -= this.mOffset;
        if (this.mDigitsLen == 0)
        {
            this.mOffset = 0;
            this.mDecPointPos = 1;
            this.mPositive = true;
        }
    }

    private void addOneToDecHex()
    {
        if ((this.mVal1 & 0xFFFFFFFFL) == 0x99999999L)
        {
            this.mVal1 = 0;
            if ((this.mVal2 & 0xFFFFFFFFL) == 0x99999999L)
            {
                this.mVal2 = 0;
                if ((this.mVal3 & 0xFFFFFFFFL) == 0x99999999L)
                {
                    this.mVal3 = 0;
                    this.mVal4 = addOneToDecHex(this.mVal4);
                }
                else
                {
                    this.mVal3 = addOneToDecHex(this.mVal3);
                }
            }
            else
            {
                this.mVal2 = addOneToDecHex(this.mVal2);
            }
        }
        else
        {
            this.mVal1 = addOneToDecHex(this.mVal1);
        }
    }

    // Assume val != 0x99999999
    private static /*uint*/long addOneToDecHex(/*uint*/long val)
    {
        if ((val & 0xffff) == 0x9999)
        {
            if ((val & 0xffffff) == 0x999999)
            {
                if ((val & 0xfffffff) == 0x9999999)
                {
                    return val + 0x06666667;
                }
                return val+ 0x00666667;
            }
            if ((val & 0xfffff) == 0x99999)
            {
                return val + 0x00066667;
            }
            return val+ 0x00006667;
        }
        if ((val & 0xff) == 0x99)
        {
            if ((val & 0xfff) == 0x999)
            {
                return val + 0x00000667;
            }
            return val + 0x00000067;
        }
        if ((val & 0xf) == 0x9)
        {
            return val + 0x00000007;
        }
        return val + 1;
    }

    private int countTrailingZeros()
    {
        if (this.mVal1 != 0)
        {
            return countTrailingZeros(this.mVal1);
        }
        if (this.mVal2 != 0)
        {
            return countTrailingZeros(this.mVal2) + 8;
        }
        if (this.mVal3 != 0)
        {
            return countTrailingZeros(this.mVal3) + 16;
        }
        if (this.mVal4 != 0)
        {
            return countTrailingZeros(this.mVal4) + 24;
        }
        return this.mDigitsLen;
    }

    private static int countTrailingZeros(/*uint*/long val)
    {
        if ((val & 0xffff) == 0)
        {
            if ((val & 0xffffff) == 0)
            {
                if ((val & 0xfffffff) == 0)
                {
                    return 7;
                }
                return 6;
            }
            if ((val & 0xfffff) == 0)
            {
                return 5;
            }
            return 4;
        }
        if ((val & 0xff) == 0)
        {
            if ((val & 0xfff) == 0)
            {
                return 3;
            }
            return 2;
        }
        if ((val & 0xf) == 0)
        {
            return 1;
        }
        return 0;
    }

