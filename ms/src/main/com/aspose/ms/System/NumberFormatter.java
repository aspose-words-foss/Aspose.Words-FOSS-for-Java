        this.mSpecifier = specifier;
        if (format.length() > 1)
        {
            this.mPrecision = parsePrecision(format);
            if (this.mPrecision == -2)
            {
                // Is it a custom format?
                this.mIsCustomFormat = true;
                this.mSpecifier = '0';
                this.mPrecision = -1;
            }
        }
